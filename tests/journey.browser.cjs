const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const http = require('node:http');
const root = path.resolve(__dirname, '..');
const server = http.createServer((req, res) => {
    const file = path.resolve(root, '.' + (req.url === '/' ? '/index.html' : decodeURIComponent(req.url.split('?')[0])));
    if (!file.startsWith(root + path.sep)) return res.writeHead(403).end();
    fs.readFile(file, (err, body) => {
        if (err) return res.writeHead(404).end();
        res.setHeader('Content-Type', ({'.html':'text/html', '.js':'text/javascript', '.css':'text/css', '.png':'image/png'})[path.extname(file)] || 'application/octet-stream');
        res.end(body);
    });
});
(async () => {
    await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
    const browser = await chromium.launch({headless:true, executablePath:process.env.BROWSER_PATH || 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'});
    try {
        fs.mkdirSync(path.join(root, 'tmp'), {recursive:true});
        const page = await browser.newPage({viewport:{width:1365,height:900}});
        const errors = [];
        page.on('pageerror', e => errors.push(e.message));
        await page.route('https://fonts.googleapis.com/**', route => route.abort());
        await page.goto(`http://127.0.0.1:${server.address().port}`);
        const total = await page.evaluate(() => Object.keys(departmentGames).length);
        const close = () => page.locator('#journey-close').click();
        assert.equal(await page.locator('.journey-actions [data-journey="recommendation"]').isVisible(), false);
        await page.locator('.journey-actions [data-journey="certificate"]').click();
        assert.match(await page.locator('canvas').getAttribute('aria-label'), new RegExp(`0/${total}`));
        const zeroSummary = await page.locator('canvas').evaluate(el=>JSON.parse(el.dataset.certificateSummary));
        assert.equal(zeroSummary.average,null);
        assert(zeroSummary.groups.every(group=>group.percent===null));
        assert.equal(zeroSummary.rows.length,total);
        const downloadEvent = page.waitForEvent('download');
        await page.locator('.journey-download').click();
        const download = await downloadEvent;
        await download.saveAs(path.join(root, 'tmp/journey-zero.png'));
        const png = fs.readFileSync(path.join(root, 'tmp/journey-zero.png'));
        assert.equal(png.readUInt32BE(16),1400); assert.equal(png.readUInt32BE(20),1000);
        await page.keyboard.press('Escape');
        assert.equal(await page.locator('#journey-dialog').evaluate(el => el.open), false);
        await page.evaluate(() => { for (let id=1; id<=5; id++) awardGameBadge(id); });
        await page.locator('.journey-actions [data-journey="recommendation"]').click();
        assert.match(await page.locator('#journey-content').innerText(), /Henüz yeterli veri yok/);
        await close();
        await page.evaluate(() => {
            awardGameBadge(1,{score:9,total:10,won:true});
            awardGameBadge(2,{score:4,total:5,won:true});
            awardGameBadge(3,{score:7,total:10,won:true});
            awardGameBadge(4,{score:3,total:5,won:true});
            awardGameBadge(5,{score:8,total:10,won:true});
            awardGameBadge(1,{score:1,total:10,won:false});
            awardGameBadge(6,{score:1,total:5,won:false});
        });
        const result = await page.evaluate(() => ({r:journeyData.recommendation(completedDepts),scores:journeyData.scores(),badges:completedDepts}));
        assert.equal(result.r.winner.family,'insan'); assert.equal(result.r.strongest,1);
        assert.equal(result.r.families.find(v=>v.family==='ticari').average,70);
        assert.equal(result.scores[1].percent,90); assert.equal(result.badges.length,5);
        await page.evaluate(() => journey.open('recommendation'));
        await page.screenshot({path:path.join(root,'tmp/journey-recommendation.png')});
        await close();
        await page.evaluate(() => enterDepartment(7));
        await page.locator('#room-explore-toggle').click();
        await page.locator('#room-explore-menu [data-spot]').first().click();
        const note = await page.evaluate(() => departmentsData[7].hotspots[0]);
        await page.reload();
        assert.equal(await page.evaluate(() => journeyData.scores()[1].percent),90);
        assert.deepEqual(await page.evaluate(() => roomExplore.notes()[7]),[note.id]);
        await page.locator('.journey-actions [data-journey="notes"]').click();
        assert.match(await page.locator('[data-note-dept="7"]').innerText(),new RegExp(note.title));
        assert.equal(await page.locator('.journey-unvisited').count(),total - 6);
        await page.screenshot({path:path.join(root,'tmp/journey-notes.png')});
        await close();
        await page.evaluate(() => {enterDepartment(7); exitDepartment();});
        assert.equal(await page.locator('.door-btn.next-destination').getAttribute('data-dept-id'),'7');
        await page.evaluate(() => {for(let id=6;id<=10;id++) awardGameBadge(id,{score:5,total:5,won:true});});
        assert.equal(await page.locator('#floor-btn.next-destination').count(),1);
        await page.evaluate(() => {for(const id of Object.keys(departmentGames).map(Number).filter(id=>id>10)) awardGameBadge(id,{score:5,total:5,won:true});});
        assert.equal(await page.locator('#lounge-btn.next-destination').count(),1);
        await page.locator('#lounge-btn').click();
        assert.match(await page.locator('#journey-content').innerText(),/Yolculuk tamamlandı/);
        await page.locator('#journey-content [data-journey="certificate"]').click();
        assert.match(await page.locator('canvas').getAttribute('aria-label'),new RegExp(`${total}/${total}`));
        const certificateData = await page.locator('canvas').evaluate(el=>JSON.parse(el.dataset.certificateSummary));
        assert.equal(certificateData.average,94);
        assert.equal(certificateData.groups.find(group=>group.label==='Ticari').percent,85);
        assert.equal(certificateData.rows.find(row=>row.id===1).score.percent,90);
        assert.match(await page.locator('.certificate-text-summary').textContent(),/Genel oyun ortalaması: %94.0/);
        fs.writeFileSync(path.join(root,'tmp/journey-certificate.png'),Buffer.from(await page.locator('canvas').evaluate(el=>el.toDataURL().split(',')[1]),'base64'));
        await close();
        await page.setViewportSize({width:390,height:844});
        await page.locator('.journey-mobile-actions [data-journey="notes"]').click();
        assert(await page.locator('#journey-dialog').evaluate(el=>el.scrollWidth<=el.clientWidth+1));
        await page.screenshot({path:path.join(root,'tmp/journey-mobile.png')});
        await close();
        await page.emulateMedia({reducedMotion:'reduce'});
        assert.equal(await page.locator('.next-destination').evaluate(el=>getComputedStyle(el).animationName),'none');
        await page.evaluate(() => {localStorage.setItem('flo-room-notes','broken');localStorage.setItem('flo-game-scores','broken');});
        await page.reload();
        assert.deepEqual(await page.evaluate(() => journeyData.scores()),{});
        assert.deepEqual(await page.evaluate(() => roomExplore.notes()),{});
        assert.deepEqual(errors,[]);
        console.log('PASS: scores, legacy fallback, recommendation, notes persistence, door guidance, PNG download, mobile and reduced motion.');
    } finally {await browser.close();server.close();}
})().catch(error => {console.error(error);process.exitCode=1;server.close();});
